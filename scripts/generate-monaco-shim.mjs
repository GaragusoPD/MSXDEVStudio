#!/usr/bin/env node
// Regenerates src/renderer/src/editors/monaco-full.ts from monaco-editor's own
// `esm/vs/index.js` (what `import * as monaco from 'monaco-editor'` runs) —
// same import list (every basic-language definition, every editor contrib
// feature), minus the css/html/typescript "rich language" features and the
// unused monaco-lsp-client bridge. Each of the three dropped features bundles
// its own multi-megabyte language-server worker (ts.worker.js alone is
// ~13 MB) that this IDE never triggers (getWorker() in monaco-setup.ts only
// ever hands out the json/editor workers) — dead weight in every installer.
// `json` is kept (this IDE does open plain .json files) as a plain import;
// its namespace export is dropped since nothing here reads `monaco.json`.
//
// Rerun after bumping monaco-editor: `npm run monaco:shim`, then diff — a
// version bump can add/remove languages or features upstream.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = join(ROOT, 'node_modules/monaco-editor/esm/vs/index.js')
const OUTPUT = join(ROOT, 'src/renderer/src/editors/monaco-full.ts')

const DROP = ['external/monaco-lsp-client', 'features/css/register', 'features/html/register', 'features/typescript/register']
const SIDE_EFFECT_ONLY = ['features/json/register'] // keep the import, drop its namespace export

const lines = readFileSync(SOURCE, 'utf-8').split('\n')
const out = []
let skipNextExport = false

for (const line of lines) {
  const namedImport = /^import \* as \w+ from '(\.\/[^']+)';$/.exec(line)
  const plainImport = /^import '(\.\/[^']+)';$/.exec(line)
  const finalExport = /^export \{ (.+) \} from '(\.\/[^']+)';$/.exec(line)

  if (namedImport) {
    const [, path] = namedImport
    if (DROP.some((marker) => path.includes(marker))) {
      skipNextExport = true
      continue
    }
    if (SIDE_EFFECT_ONLY.some((marker) => path.includes(marker))) {
      out.push(`import '@monaco${path.slice(1)}'`)
      skipNextExport = true
      continue
    }
    // No other named-namespace imports are expected from this source file.
    throw new Error(`generate-monaco-shim: unhandled named import: ${line}`)
  }
  if (skipNextExport) {
    skipNextExport = false
    continue
  }
  if (plainImport) {
    out.push(`import '@monaco${plainImport[1].slice(1)}'`)
    continue
  }
  if (finalExport) {
    out.push(`export { ${finalExport[1]} } from '@monaco${finalExport[2].slice(1)}'`)
  }
}

const header = `// GENERATED by scripts/generate-monaco-shim.mjs — do not hand-edit.
// Regenerate: npm run monaco:shim
// A trimmed drop-in for \`import * as monaco from 'monaco-editor'\`. See the
// generator script for what's dropped and why (short version: unused
// css/html/typescript language-server workers, ~16 MB of dead install size).
// '@monaco' is a Vite alias (electron.vite.config.ts) to monaco-editor's
// esm/vs/ directory — used instead of the package's own subpath exports
// because that export map only rewrites '.js'-suffixed specifiers, breaking
// the .css imports below.
`

writeFileSync(OUTPUT, header + '\n' + out.join('\n') + '\n')
console.log(`Wrote ${out.length} import/export lines to ${OUTPUT.replace(ROOT + '/', '')}`)
